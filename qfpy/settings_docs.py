def key_title(key: str) -> str:
    """差异列表里显示的名字：好懂的中文名 + 英文键名（小字由页面处理，这里用括号）。"""
    k = str(key)
    d = DOCS.get(k)
    if d is None and k.startswith("exits.by_pool."):
        rest = k[len("exits.by_pool."):]
        pool, _, sub = rest.rpartition(".")
        sd = DOCS.get(f"exits.{sub}")
        if pool and sd:
            return f"按股池 {pool}：{sd['title']}（{k}）"
    if d is None and k.startswith("select.weights."):
        return f"打分权重：{k.split('.', 2)[2]}（{k}）"
    return f"{d['title']}（{k}）" if d else k


def docs() -> dict[str, dict[str, str]]:
    return {k: dict(v) for k, v in DOCS.items()}
